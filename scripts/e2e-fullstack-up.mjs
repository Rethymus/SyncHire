#!/usr/bin/env node
/**
 * Start the FULL-STACK e2e environment locally (requires Docker):
 *
 *   1. postgres (pgvector/pgvector:pg16) on localhost:55432  — ephemeral, no volume
 *   2. redis (redis:7.2-alpine)           on localhost:56379  — ephemeral, no volume
 *   3. the full FastAPI backend (api/main.py) on http://localhost:8010
 *      (init_db() runs create_all on startup, so no alembic step is needed)
 *
 * Everything is isolated from the shared dev stack: host ports 55432/56379/8010
 * (never 5432/6379/8000) and a dedicated docker compose project `synchire-e2e`.
 *
 * After this succeeds, run the tests:
 *   cd frontend && npm run test:e2e:fullstack
 * Then tear down:
 *   node scripts/e2e-fullstack-down.mjs
 *
 * If Docker is not installed, the full-stack spec simply skips locally; the
 * equivalent backend is started by the CI `fullstack-e2e` job.
 */

import { spawn, spawnSync } from 'node:child_process'
import { mkdirSync, writeFileSync, rmSync, existsSync, readFileSync, openSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('..', import.meta.url))
const tmpDir = path.join(root, 'tmp')
const apiDir = path.join(root, 'api')

const API_PORT = process.env.FULLSTACK_API_PORT ?? '8010'
const FRONTEND_PORT = process.env.FULLSTACK_FRONTEND_PORT ?? '3100'
const PG_PORT = process.env.FULLSTACK_PG_PORT ?? '55432'
const REDIS_PORT = process.env.FULLSTACK_REDIS_PORT ?? '56379'
const API_URL = process.env.FULLSTACK_API_URL ?? `http://localhost:${API_PORT}`

const COMPOSE_FILE = path.join(tmpDir, 'e2e-fullstack-compose.yml')
const PID_FILE = path.join(tmpDir, 'e2e-fullstack-api.pid')
const LOG_FILE = path.join(tmpDir, 'e2e-fullstack-api.log')

const PG_USER = 'synchire_e2e'
const PG_PASSWORD = 'synchire_e2e'
const PG_DB = 'synchire_e2e'

const composeFileContent = `# Generated by scripts/e2e-fullstack-up.mjs — isolated full-stack e2e services.
services:
  postgres:
    image: pgvector/pgvector:pg16
    container_name: synchire-e2e-postgres
    environment:
      POSTGRES_USER: ${PG_USER}
      POSTGRES_PASSWORD: ${PG_PASSWORD}
      POSTGRES_DB: ${PG_DB}
    ports:
      - "${PG_PORT}:5432"
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U ${PG_USER}"]
      interval: 5s
      timeout: 5s
      retries: 10
  redis:
    image: redis:7.2-alpine
    container_name: synchire-e2e-redis
    ports:
      - "${REDIS_PORT}:6379"
    healthcheck:
      test: ["CMD", "redis-cli", "ping"]
      interval: 5s
      timeout: 3s
      retries: 10
`

const composeArgs = ['-f', COMPOSE_FILE, '-p', 'synchire-e2e']

function run(command, args, opts = {}) {
  return spawnSync(command, args, { encoding: 'utf8', shell: false, ...opts })
}

function fail(message) {
  console.error(`[e2e-fullstack-up] ERROR: ${message}`)
  process.exit(1)
}

async function waitFor(check, timeoutMs) {
  const startedAt = Date.now()
  while (Date.now() - startedAt < timeoutMs) {
    if (await check()) return true
    await new Promise(resolve => setTimeout(resolve, 1500))
  }
  return false
}

async function apiHealthy() {
  try {
    const response = await fetch(`${API_URL}/health`, { signal: AbortSignal.timeout(2000) })
    if (!response.ok) return false
    const body = await response.json()
    return body?.status === 'healthy'
  } catch {
    return false
  }
}

function tailLogFile(lines = 40) {
  try {
    const content = readFileSync(LOG_FILE, 'utf8').trim()
    if (content) console.error(content.split('\n').slice(-lines).join('\n'))
  } catch {
    /* no log yet */
  }
}

// --- 0. Preflight -------------------------------------------------------------
mkdirSync(tmpDir, { recursive: true })

if (process.env.SKIP_FULLSTACK === '1') {
  fail('SKIP_FULLSTACK=1 is set — no point starting the full-stack environment.')
}

const dockerVersion = run('docker', ['--version'])
if (dockerVersion.error || dockerVersion.status !== 0) {
  fail(
    'Docker is not available. The full-stack e2e only runs locally with Docker; ' +
      'without it the spec self-skips. CI runs it in the fullstack-e2e job.'
  )
}
const composeVersion = run('docker', ['compose', 'version'])
if (composeVersion.error || composeVersion.status !== 0) {
  fail('`docker compose` (v2 plugin) is not available.')
}

// --- 1. Start postgres + redis ------------------------------------------------
writeFileSync(COMPOSE_FILE, composeFileContent)

console.log('[e2e-fullstack-up] starting postgres + redis (docker compose)...')
const up = run('docker', [...composeArgs, 'up', '-d', '--wait'])
if (up.status !== 0) {
  console.error(up.stdout)
  console.error(up.stderr)
  run('docker', [...composeArgs, 'down', '-v', '--remove-orphans'])
  fail('docker compose up failed (see output above).')
}
console.log(
  `[e2e-fullstack-up] postgres ready on :${PG_PORT}, redis ready on :${REDIS_PORT} (ephemeral, no volumes)`
)

// --- 2. Start the backend on :8010 --------------------------------------------
if (await apiHealthy()) {
  console.log(`[e2e-fullstack-up] backend already healthy at ${API_URL} — reusing it.`)
} else {
  if (existsSync(PID_FILE)) {
    console.warn('[e2e-fullstack-up] stale pid file found — run e2e-fullstack-down.mjs first if a backend is stuck.')
    rmSync(PID_FILE, { force: true })
  }

  const backendEnv = {
    ...process.env,
    DATABASE_URL: `postgresql+asyncpg://${PG_USER}:${PG_PASSWORD}@localhost:${PG_PORT}/${PG_DB}`,
    REDIS_URL: `redis://localhost:${REDIS_PORT}`,
    // The frontend dev server for these tests runs on FRONTEND_PORT.
    CORS_ORIGINS: `http://localhost:${FRONTEND_PORT},http://127.0.0.1:${FRONTEND_PORT}`,
    JWT_SECRET: 'synchire-e2e-jwt-secret',
    PYTHONUNBUFFERED: '1',
  }

  const logFd = openSync(LOG_FILE, 'w')
  const child = spawn(
    process.platform === 'win32' ? 'python' : 'python3',
    ['-m', 'uvicorn', 'main:app', '--host', '127.0.0.1', '--port', API_PORT],
    { cwd: apiDir, env: backendEnv, detached: true, stdio: ['ignore', logFd, logFd], windowsHide: true }
  )
  child.unref()
  writeFileSync(PID_FILE, String(child.pid))
  console.log(`[e2e-fullstack-up] backend starting (pid ${child.pid}) on :${API_PORT}, log: ${LOG_FILE}`)

  const ready = await waitFor(apiHealthy, 90_000)
  if (!ready) {
    console.error(`[e2e-fullstack-up] backend at ${API_URL} did not become healthy in 90s. Last log lines:`)
    tailLogFile()
    console.error('[e2e-fullstack-up] run scripts/e2e-fullstack-down.mjs to clean up the containers.')
    process.exit(1)
  }
  console.log(`[e2e-fullstack-up] backend healthy at ${API_URL}`)
}

console.log('')
console.log('[e2e-fullstack-up] environment ready:')
console.log(`  API:       ${API_URL}/health`)
console.log(`  Frontend:  npm run test:e2e:fullstack   (in frontend/, dev server on :${FRONTEND_PORT})`)
console.log('  Teardown:  node scripts/e2e-fullstack-down.mjs')
